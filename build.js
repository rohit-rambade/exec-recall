#!/usr/bin/env node
/**
 * Exec Recall builder
 * Scans content/<tech>/*.md and writes site-data.js, which index.html loads.
 *
 *   node build.js          build once
 *   node build.js --watch  rebuild whenever a file in content/ changes
 *
 * Folder rules
 *   content/<tech>/_meta.json   optional: { title, description, icon, color, position, order: [...] }
 *   content/<tech>/*.md         one topic per file (files starting with "_" are ignored)
 *
 * Topic order (first match wins)
 *   1. front matter  "order: 3"
 *   2. position in _meta.json "order" list (matched by title or file name, case/punctuation-insensitive)
 *   3. numeric file prefix  "03-linq.md"
 *   4. alphabetical
 */
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const CONTENT = path.join(ROOT, "content");
const OUT = path.join(ROOT, "site-data.js");

const norm = (s) => String(s).toLowerCase().replace(/\.md$/, "").replace(/[^a-z0-9#+]/g, "");
const slugify = (s) =>
  String(s).toLowerCase().replace(/^\d+[-_. ]+/, "").replace(/\.md$/, "")
    .replace(/[#]/g, "sharp").replace(/\+/g, "plus")
    .replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "topic";

function parseFrontMatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!m) return { fm: {}, body: text };
  const fm = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^\s*([A-Za-z_][\w-]*)\s*:\s*(.*)$/);
    if (kv) fm[kv[1]] = kv[2].replace(/^["']|["']$/g, "").trim();
  }
  return { fm, body: text.slice(m[0].length) };
}

function readJson(file) {
  try { return JSON.parse(fs.readFileSync(file, "utf8")); }
  catch (e) { if (fs.existsSync(file)) console.warn(`! Could not parse ${file}: ${e.message}`); return {}; }
}

function build() {
  if (!fs.existsSync(CONTENT)) fs.mkdirSync(CONTENT, { recursive: true });
  const techs = [];

  for (const dir of fs.readdirSync(CONTENT, { withFileTypes: true })) {
    if (!dir.isDirectory() || dir.name.startsWith("_") || dir.name.startsWith(".")) continue;
    const techDir = path.join(CONTENT, dir.name);
    const meta = readJson(path.join(techDir, "_meta.json"));
    const orderList = (meta.order || []).map(norm);
    const usedIds = new Set();

    const topics = fs.readdirSync(techDir)
      .filter((f) => f.toLowerCase().endsWith(".md") && !f.startsWith("_"))
      .map((file) => {
        const raw = fs.readFileSync(path.join(techDir, file), "utf8").replace(/^﻿/, "");
        const { fm, body } = parseFrontMatter(raw);
        const h1 = body.match(/^#\s+(.+?)\s*#*\s*$/m);
        const title = fm.title || (h1 ? h1[1].replace(/\\(.)/g, "$1") : file.replace(/^\d+[-_. ]+/, "").replace(/\.md$/i, ""));
        let id = slugify(fm.slug || file);
        while (usedIds.has(id)) id += "-2";
        usedIds.add(id);

        let rank = Infinity;
        if (fm.order !== undefined && !isNaN(+fm.order)) rank = +fm.order;
        else {
          const i = orderList.findIndex((o) => o === norm(title) || o === norm(file));
          if (i >= 0) rank = i;
          else { const p = file.match(/^(\d+)/); if (p) rank = 1000 + +p[1]; }
        }
        return { id, title, file: `content/${dir.name}/${file}`, rank, md: body,
                 updated: fs.statSync(path.join(techDir, file)).mtime.toISOString().slice(0, 10) };
      })
      .sort((a, b) => a.rank - b.rank || a.title.localeCompare(b.title))
      .map(({ rank, ...t }) => t);

    techs.push({
      id: slugify(dir.name),
      title: meta.title || dir.name,
      description: meta.description || "",
      icon: meta.icon || dir.name.slice(0, 2).toUpperCase(),
      color: meta.color || "#6366f1",
      position: meta.position ?? 999,
      topics,
    });
  }

  techs.sort((a, b) => a.position - b.position || a.title.localeCompare(b.title));
  const site = { ...readJson(path.join(CONTENT, "_site.json")), generated: new Date().toISOString(), techs };
  fs.writeFileSync(OUT, "/* Generated by build.js. Do not edit by hand. */\nwindow.SITE_DATA = " + JSON.stringify(site) + ";\n");
  const total = techs.reduce((n, t) => n + t.topics.length, 0);
  console.log(`✓ Built site-data.js: ${techs.length} technologies, ${total} topics`);
  for (const t of techs) console.log(`  ${t.title.padEnd(14)} ${t.topics.length} topic(s)`);
}

build();

if (process.argv.includes("--watch")) {
  let timer;
  console.log("Watching content/ for changes… (Ctrl+C to stop)");
  fs.watch(CONTENT, { recursive: true }, () => {
    clearTimeout(timer);
    timer = setTimeout(() => { try { build(); } catch (e) { console.error(e.message); } }, 200);
  });
}
